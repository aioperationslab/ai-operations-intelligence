import { NextResponse } from "next/server";
import { buildAIContext } from "@/app/lib/ai/context";
import { getAIProvider } from "@/app/lib/ai/providers";
import { DEFAULT_AI_PROVIDER } from "@/app/lib/ai/config";

export async function POST(request: Request) {
  try {
    const body = await request.json();
    const question = body.question?.trim();

    if (!question) {
      return NextResponse.json(
        {
          success: false,
          message: "Please provide a question.",
        },
        { status: 400 }
      );
    }

    // Build operational context from Neo4j and retrieved documents.
    const context = await buildAIContext(question);

    // Use the configured provider.
    const configuredProvider = DEFAULT_AI_PROVIDER;

    const provider = getAIProvider(configuredProvider);

    const aiResponse = await provider.generateResponse({
      question,
      context,
    });

    // Preserve the existing graph and document structures.
    const graphData = context.graph.records ?? [];
    const documentData = context.documents.records ?? [];

    // Unified result collection.
    const results = [
      ...graphData.map((record) => ({
        type: "graph",
        data: record,
      })),
      ...documentData.map((record) => ({
        type: "document",
        data: record,
      })),
    ];

    const resultCount = results.length;

    // Simple evidence-based confidence for the current
    // rule-based agent. This is intentionally deterministic
    // and does not require an LLM call.
    let confidence: "high" | "medium" | "low";

    if (graphData.length > 0 && documentData.length > 0) {
      confidence = "high";
    } else if (graphData.length > 0 || documentData.length > 0) {
      confidence = "medium";
    } else {
      confidence = "low";
    }

    return NextResponse.json({
      success: true,

      // Original question.
      question,

      // Classification of the requested intelligence.
      responseType: context.responseType,

      // Human-readable answer generated by the active provider.
      answer: aiResponse.answer,

      // AI provider information.
      provider: aiResponse.provider,
      configuredProvider,

      // Standardized result contract.
      results,
      resultCount,
      confidence,

      // Preserve the existing response fields so the current
      // frontend continues to work.
      graphData,
      documentData,

      // Evidence and source information.
      sources: context.sources,

      source: context.graph.source,

      // Existing context metadata.
      metadata: context.metadata,
    });
  } catch (error) {
    console.error("AI Agent error:", error);

    return NextResponse.json(
      {
        success: false,
        message:
          "The AI Agent could not query the knowledge graph.",
      },
      { status: 500 }
    );
  }
}